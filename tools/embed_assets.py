"""Generates Assets.h with the panel images embedded in the firmware.

In AP mode there is no internet, so the panel cannot fetch images elsewhere.

- docs/esp01-pinout.svg: spaces between tags removed, then gzipped (served
  with Content-Encoding: gzip). Its URL carries a hash of the content (?v=),
  so the browser keeps it for a year and a new drawing is another URL. The
  text stays in English; web/i18n.js translates it with web/i18n.tsv.
- docs/esp-01.jpg: cropped at the white edges, PHOTO_WIDTH px wide (the size
  it is shown at), on its white background, then AVIF at the finest quality
  that fits in PHOTO_BYTES. No alpha: a transparent background showed the
  board loose on the dark page and cost bytes the picture now gets. The browser decodes AVIF itself: the firmware carries no
  decoder.

Usage: python tools/embed_assets.py (needs Pillow 11.3 or newer, with AVIF).
The generated Assets.h goes into the repository: the build does not need this tool.
"""
import gzip
import hashlib
import io
import os
import re

try:
    import zopfli.gzip as _zopfli
except ImportError:  # optional: only makes the gzip smaller
    _zopfli = None

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
PHOTO_WIDTH = 220
PHOTO_BYTES = 1500   # a decoration on Home: the flash went to the IoT card


def pinout():
    with open(os.path.join(ROOT, "docs", "esp01-pinout.svg"), "rb") as f:
        svg = re.sub(rb"<!--.*?-->", b"", f.read(), flags=re.S)  # license header
        svg = re.sub(rb">\s+<", b"><", svg).strip()
    tag = hashlib.sha256(svg).hexdigest()[:8]
    if _zopfli:
        return _zopfli.compress(svg, numiterations=1000), tag
    return gzip.compress(svg, 9, mtime=0), tag


def photo():
    from PIL import Image

    im = Image.open(os.path.join(ROOT, "docs", "esp-01.jpg")).convert("RGB")
    # Crops the white background: anything above 245 in gray counts as border
    box = Image.eval(im.convert("L"), lambda v: 255 if v < 245 else 0).getbbox()
    im = im.crop(box)
    height = round(im.height * PHOTO_WIDTH / im.width)
    im = im.resize((PHOTO_WIDTH, height), Image.LANCZOS)
    # No metadata: the JPEG's ICC profile (sRGB, what browsers assume
    # anyway) alone is 3 KB
    im.info = {}
    # The size does not always grow with the quality: every one is tried
    # (0 is not the lowest: Pillow takes it as the default)
    best = None
    for quality in range(1, 101):
        out = io.BytesIO()
        im.save(out, "AVIF", quality=quality, speed=0)
        if len(out.getvalue()) <= PHOTO_BYTES:
            best = (out.getvalue(), quality)
    if not best:
        raise SystemExit(f"the photo does not fit in {PHOTO_BYTES} bytes even at quality 1")
    return best[0], best[1], im.size


def array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16])
            for i in range(0, len(data), 16)]
    body = ",\n    ".join(rows)
    return f"static const uint8_t {name}[] PROGMEM = {{\n    {body}\n}};\n"


def main():
    svg, svg_tag = pinout()
    avif, quality, (w, h) = photo()
    text = (
        "// SPDX-License-Identifier: MIT\n"
        "// Copyright (c) 2026 Allan Barcelos. ESP8266 IoT: "
        "https://github.com/allanbarcelos/esp8266-iot\n\n"
        "#pragma once\n"
        "// Generated by tools/embed_assets.py from docs/. Do not edit.\n"
        "#include <Arduino.h>\n\n"
        f"// ESP-01 photo, AVIF {w}x{h}, white background ({len(avif)} bytes)\n"
        + array("ASSET_PHOTO", avif) +
        f"\n// ESP-01 pinout, gzipped SVG ({len(svg)} bytes)\n"
        f'#define ASSET_PINOUT_TAG "{svg_tag}"\n'
        + array("ASSET_PINOUT_GZ", svg)
    )
    with open(os.path.join(ROOT, "Assets.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"Assets.h: photo {w}x{h} AVIF quality {quality}, {len(avif)} B; pinout {len(svg)} B")


if __name__ == "__main__":
    main()
