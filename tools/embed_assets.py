"""Generates Assets.h with the panel's pinout drawing embedded in the firmware.

In AP mode there is no internet, so the panel cannot fetch images elsewhere.

- docs/esp01-pinout.svg: spaces between tags removed, then gzipped (served
  with Content-Encoding: gzip). Its URL carries a hash of the content (?v=),
  so the browser keeps it for a year and a new drawing is another URL. The
  text stays in English; web/i18n.js translates it with web/i18n.tsv.
Usage: python tools/embed_assets.py
The generated Assets.h goes into the repository: the build does not need this tool.
"""
import gzip
import hashlib
import os
import re

try:
    import zopfli.gzip as _zopfli
except ImportError:  # optional: only makes the gzip smaller
    _zopfli = None

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def pinout():
    with open(os.path.join(ROOT, "docs", "esp01-pinout.svg"), "rb") as f:
        svg = re.sub(rb"<!--.*?-->", b"", f.read(), flags=re.S)  # license header
        svg = re.sub(rb">\s+<", b"><", svg).strip()
    tag = hashlib.sha256(svg).hexdigest()[:8]
    if _zopfli:
        return _zopfli.compress(svg, numiterations=1000), tag
    return gzip.compress(svg, 9, mtime=0), tag


def array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16])
            for i in range(0, len(data), 16)]
    body = ",\n    ".join(rows)
    return f"static const uint8_t {name}[] PROGMEM = {{\n    {body}\n}};\n"


def main():
    svg, svg_tag = pinout()
    text = (
        "// SPDX-License-Identifier: MIT\n"
        "// Copyright (c) 2026 Allan Barcelos. ESP8266 IoT: "
        "https://github.com/allanbarcelos/esp8266-iot\n\n"
        "#pragma once\n"
        "// Generated by tools/embed_assets.py from docs/. Do not edit.\n"
        "#include <Arduino.h>\n\n"
        f"// ESP-01 pinout, gzipped SVG ({len(svg)} bytes)\n"
        f'#define ASSET_PINOUT_TAG "{svg_tag}"\n'
        + array("ASSET_PINOUT_GZ", svg)
    )
    with open(os.path.join(ROOT, "Assets.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"Assets.h: pinout {len(svg)} B")


if __name__ == "__main__":
    main()
