"""Generates RelayScript.h with the remote access Worker (relay/worker.mjs),
which the device uploads to the user's Cloudflare account itself.

The script is minified (comments, indentation and blank lines out) and then
byte-pair encoded: every byte value the text cannot hold (it is printable
ASCII and newlines) is a code that stands for a pair of bytes, which may be
codes themselves. That is 160 codes: 0x7F to 0xFF, then 0x00 to 0x1F
without the newline. The device expands it as it sends it
(CloudflareSetup.h), with a stack of a few bytes. About 46% of the minified
size, for a decoder of a few dozen bytes (gzip would need an inflater and a
32 KB window).

    python3 tools/embed_relay.py              generates RelayScript.h
    python3 tools/embed_relay.py --check      only checks (CI uses it); error if different
    python3 tools/embed_relay.py --min FILE   also writes the minified script (CI runs the
                                              Worker tests on it)

The Worker's VERSION must match RelayService::PROTOCOL.
"""
import collections
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "relay", "worker.mjs")
SERVICE = os.path.join(ROOT, "RelayService.h")
OUT = os.path.join(ROOT, "RelayScript.h")
# The codes, in the order of RELAY_PAIRS
CODES = list(range(0x7F, 0x100)) + [b for b in range(0x20) if b != 0x0A]
MAX_DEPTH = 20   # the device's expansion stack holds MAX_DEPTH + 1 bytes


def minify(src):
    out = []
    for line in src.replace("\r\n", "\n").split("\n"):
        t = line.strip()
        if not t or t.startswith("//"):
            continue
        # A comment at the end of a line; the script has no "//" inside text
        # after a space (URLs have "://")
        t = re.sub(r"\s+//[^'\"`]*$", "", t)
        out.append(t)
    text = "\n".join(out) + "\n"
    bad = sorted({c for c in text if ord(c) > 126 or (ord(c) < 32 and c != "\n")})
    if bad:
        sys.exit(f"ERROR: relay/worker.mjs must be plain ASCII once minified: {bad!r}")
    return text.encode("ascii")


def encode(data):
    """Byte-pair encoding: (pairs, codes, depth of the deepest code)."""
    data = list(data)
    pairs = []
    depth = {}
    for code in CODES:
        counts = collections.Counter(zip(data, data[1:]))
        if not counts:
            break
        (a, b), n = counts.most_common(1)[0]
        if n < 3:
            break
        pairs.append((a, b))
        depth[code] = 1 + max(depth.get(a, 0), depth.get(b, 0))
        out = []
        i = 0
        while i < len(data):
            if i + 1 < len(data) and data[i] == a and data[i + 1] == b:
                out.append(code)
                i += 2
            else:
                out.append(data[i])
                i += 1
        data = out
    deepest = max(depth.values(), default=0)
    if deepest > MAX_DEPTH:
        sys.exit(f"ERROR: a byte pair {deepest} levels deep; the device expands up to {MAX_DEPTH}")
    return pairs, bytes(data), deepest


def decode(pairs, data):
    out = bytearray()
    for b in data:
        stack = [b]
        while stack:
            x = stack.pop()
            if x not in CODES[:len(pairs)]:
                out.append(x)
            else:
                a, c = pairs[CODES.index(x)]
                stack += [c, a]
    return bytes(out)


def array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"static const uint8_t {name}[] PROGMEM = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def build():
    src = open(SRC, encoding="utf-8").read()
    version = re.search(r"^const VERSION = (\d+);", src, re.M)
    protocol = re.search(r"PROTOCOL\s*=\s*(\d+);", open(SERVICE, encoding="utf-8").read())
    if not version or not protocol or version.group(1) != protocol.group(1):
        sys.exit("ERROR: relay/worker.mjs VERSION and RelayService::PROTOCOL differ")
    text = minify(src)
    pairs, data, deepest = encode(text)
    if decode(pairs, data) != text:
        sys.exit("ERROR: byte-pair round trip failed")
    flat = bytes(x for p in pairs for x in p)
    header = (
        "// SPDX-License-Identifier: MIT\n"
        "// Copyright (c) 2026 Allan Barcelos. ESP8266 IoT: https://github.com/allanbarcelos/esp8266-iot\n\n"
        "#pragma once\n"
        "// Generated by tools/embed_relay.py from relay/worker.mjs. Do not edit.\n"
        "#include <Arduino.h>\n\n"
        f"// The Worker, minified ({len(text)} bytes) and byte-pair encoded ({len(data)} bytes):\n"
        f"// a code (0x7F to 0xFF, then 0x00 to 0x1F but the newline) stands for the two\n"
        f"// bytes at 2 * its rank (in that order) in RELAY_PAIRS, each of them a byte\n"
        f"// or a code again, at most {deepest} levels deep.\n"
        f"static constexpr uint8_t RELAY_VERSION = {version.group(1)};\n"
        f"static constexpr size_t  RELAY_SCRIPT_LEN = {len(text)};\n"
        f"static constexpr uint8_t RELAY_DEPTH = {deepest};\n"
        + array("RELAY_PAIRS", flat or b"\0")
        + array("RELAY_SCRIPT", data)
    )
    return header, text, len(flat), len(data)


def main():
    header, text, npairs, ndata = build()
    if "--min" in sys.argv[1:]:
        with open(sys.argv[sys.argv.index("--min") + 1], "wb") as f:
            f.write(text)
    if "--check" in sys.argv[1:]:
        current = open(OUT, encoding="utf-8").read().replace("\r\n", "\n") if os.path.exists(OUT) else ""
        if current != header:
            sys.exit("ERROR: RelayScript.h does not match relay/worker.mjs; run python3 tools/embed_relay.py")
        print("RelayScript.h matches relay/worker.mjs")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(header)
    print(f"relay/worker.mjs: {len(text)} B minified, {ndata} + {npairs} B embedded")


if __name__ == "__main__":
    main()
